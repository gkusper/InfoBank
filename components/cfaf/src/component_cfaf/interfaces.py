"""Narrow replaceable interfaces. Authority always comes from the application."""
from typing import Protocol, Sequence
from .contracts import *

class Profiler(Protocol):
    def profile(self, query: str, as_of: str | None = None) -> RequestContract: ...
class Retriever(Protocol):
    def retrieve(self, request: RequestContract, permitted: Sequence[View]) -> list[View]: ...
class Governance(Protocol):
    def project(self, query: str, sources: Sequence[RawSource], authority: Authority) -> tuple[list[View], dict]: ...
    def current(self, authority: Authority) -> bool: ...
class ProposalProvider(Protocol):
    def propose(self, request: RequestContract, evidence: GovernedEvidenceContract) -> ProviderResult: ...
class SupportChecker(Protocol):
    def check(self, request: RequestContract, evidence: GovernedEvidenceContract, proposal: LLMProposal) -> dict: ...
class Renderer(Protocol):
    def render(self, decision: DecisionContract, proposal: LLMProposal | None, evidence: GovernedEvidenceContract) -> PublicResponseContract: ...
